#!/bin/sh
set -eu
cd "$(dirname "$0")/.."
python3 script/release-build.py -p idle-neural --target wasm32-unknown-unknown
python3 - <<'PY'
import base64
from pathlib import Path
wasm=Path('target/wasm32-unknown-unknown/release/idle_neural.wasm').read_bytes()
encoded=base64.b64encode(wasm).decode('ascii')
Path('neural-wasm.js').write_text('// Generated by script/build-neural.sh from the Rust crate.\nconst neuralBytes = Uint8Array.from(atob("'+encoded+'"), c => c.charCodeAt(0));\n')
PY
